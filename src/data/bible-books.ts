export function findMinistryVerse(
  bookNumber: number,
  chapter: number,
  verseStart: number,
  verseEnd?: number
): MinistryVerse | undefined {
  return POPULAR_MINISTRY_VERSES.find(
    (v) =>
      v.bookNumber === bookNumber &&
      v.chapter === chapter &&
      v.verseStart === verseStart &&
      (verseEnd ? v.verseEnd === verseEnd : !v.verseEnd || v.verseEnd === verseStart)
  );
}
