export function findBibleBookByNumber(bookNumber: number): BibleBook | undefined {
  return BIBLE_BOOKS.find((b) => b.bookNumber === bookNumber);
}

export function findBibleBookByNameEn(nameEn: string): BibleBook | undefined {
  const normalized = nameEn.trim().toLowerCase();
  return BIBLE_BOOKS.find((b) => b.nameEn.toLowerCase() === normalized);
}

